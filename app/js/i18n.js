// All student-facing text. Czech is the default; English is built in; 18 more languages load from lang/<code>.js when picked.
// Czech strings don't assume the student's gender. Course content stays in the language of the uploaded slides.
import { store } from "./util.js";

export const LANG_CODES = ["cs", "en", "es", "zh", "hi", "ar", "pt", "fr", "de", "ru", "ja", "bn", "id", "tr", "ko", "vi", "it", "pl", "uk", "sk"];
const RTL = ["ar"];
const D = { cs: null, en: null };
export const lang = () => { const l = store.get("lang", "cs"); return LANG_CODES.includes(l) ? l : "cs"; };
// The course language for the build: only cs and en exist server-side; other UI languages leave it to the slides.
export const courseLang = () => (lang() === "en" ? "en" : "cs");
export async function loadLang(l = lang()) {
  if (!D[l]) { try { D[l] = (await import(`./lang/${l}.js`)).default; } catch (e) { D[l] = {}; } }
}
export async function setLang(l) {
  if (!LANG_CODES.includes(l)) l = "cs";
  await loadLang(l);
  store.set("lang", l);
  document.documentElement.lang = l;
  document.documentElement.dir = RTL.includes(l) ? "rtl" : "ltr";
}
const dict = () => D[lang()] || D.en;
export const t = (k, vars) => {
  const l = lang();
  let s = dict()[k] ?? (l === "cs" ? undefined : D.en[k]) ?? D.cs[k] ?? k;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, v) => vars[v] ?? m);
  return s;
};
export const errText = code => dict()["err" + code] || (lang() !== "cs" && D.en["err" + code]) || dict().errserver || D.cs.errserver;
// Plurals by the language's own rules (Intl.PluralRules), # is the number.
export function pl(key, n) {
  const forms = dict()["pl_" + key] || D.en["pl_" + key];
  let cat = "other"; try { cat = new Intl.PluralRules(lang()).select(n); } catch (e) { }
  return (forms[cat] || forms.other).replace("#", n.toLocaleString(lang()));
}
export const days = n => pl("days", n);
export const pages = n => pl("pages", n);
export const itemCount = n => pl("items", n);
export const lessonCount = n => pl("lessons", n);
export const fileCount = n => pl("files", n);
export const inDays = n => pl("inDays", n);
export const inWeeks = n => pl("inWeeks", n);
export const minutesLeft = sec => sec < 60 ? t("lessMinLeft") : t("minLeft", { n: Math.ceil(sec / 60) });
export const voiceMinutes = sec => t("voiceLeft", { n: Math.floor(sec / 60) });
export const studyTime = ms => { const m = Math.round(ms / 60000), h = Math.floor(m / 60); return h ? t("timeHM", { h, m: m % 60 }) : t("timeM", { m }); };
// Dates in the UI language: "pá 15. ledna".
const parseD = s => { const [y, m, d] = s.split("-").map(Number); return new Date(y, m - 1, d); };
// The weekday in full: Czech "ne 20. prosince" reads as "not 20 December".
export const fmtDay = iso => { try { return parseD(iso).toLocaleDateString(lang(), { weekday: "long", day: "numeric", month: "long" }); } catch (e) { return iso; } };
export const fmtDateLong = iso => { try { return parseD(iso).toLocaleDateString(lang(), { day: "numeric", month: "long", year: "numeric" }); } catch (e) { return iso; } };
export const fmtShortMonth = d => { try { return d.toLocaleDateString(lang(), { month: "short" }).replace(".", ""); } catch (e) { return ""; } };

